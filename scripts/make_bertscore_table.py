"""
Paired-difference tables for the BERTScore re-score of COCO K=12.

    python scripts/make_bertscore_table.py

Reads results/channel/coco_k12/summary.csv (MPNet) and
summary_bertscore.csv, writes docs/channel_bertscore_tables.md and
prints LaTeX rows for the paper.
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

CHANNELS = [
    ("iid", "0.0", "i.i.d."),
    ("gilbert", "0.3", "GE rho=0.3"),
    ("gilbert", "0.6", "GE rho=0.6"),
    ("gilbert", "0.9", "GE rho=0.9"),
    ("rayleigh", "0.5", "Rayleigh alpha=0.5"),
    ("rayleigh", "0.9", "Rayleigh alpha=0.9"),
    ("rayleigh", "0.99", "Rayleigh alpha=0.99"),
]
LATEX = {"i.i.d.": "i.i.d.", "GE rho=0.3": r"GE $\rho=0.3$", "GE rho=0.6": r"GE $\rho=0.6$", "GE rho=0.9": r"GE $\rho=0.9$",
         "Rayleigh alpha=0.5": r"Rayl.\ $\alpha=0.5$", "Rayleigh alpha=0.9": r"Rayl.\ $\alpha=0.9$", "Rayleigh alpha=0.99": r"Rayl.\ $\alpha=0.99$"}
REFS = [("sempa_look", "SemPA-Look"), ("swap_ls+order", "Swap+ord"), ("full_search_iid", "FS i.i.d.")]


def load(path: Path) -> dict:
    return {(r["M"], r["channel"], r["parameter"], r["p"], r["algorithm"]): r for r in csv.DictReader(open(path))}


def gain(table: dict, M: str, channel: str, parameter: str, p: str, ref: str):
    row = table.get((M, channel, parameter, p, "casa"))
    if row is None or not row.get(f"gain_vs_{ref}"):
        return None
    key = f"gain_vs_{ref}"
    return float(row[key]), float(row[key + "_ci_low"]), float(row[key + "_ci_high"])


def fmt(g, ci: bool = True) -> str:
    if g is None:
        return "-"
    star = "" if g[1] > 0 or g[2] < 0 else " (n.s.)"
    return f"{g[0]:+.4f} [{g[1]:+.4f}, {g[2]:+.4f}]" if ci else f"{g[0]:+.3f}{star}"


def markdown(mpnet: dict, bert: dict, M: str = "2", ps=("0.3", "0.5")) -> str:
    lines = ["# CASA under BERTScore F1 (COCO, K = 12)", "",
             "Generated by `scripts/make_bertscore_table.py`. Paired difference CASA minus each reference, mean over 100 messages, "
             "with 95% paired-bootstrap CI. Same partitions; phi is MPNet cosine (design encoder) or BERTScore F1 "
             "(RoBERTa-large, baseline-rescaled).", ""]
    for p in ps:
        lines += [f"## N = {12 // int(M)}, p = {p}", "",
                  "| Channel | metric | vs " + " | vs ".join(name for _, name in REFS) + " |",
                  "|---|---|" + "---|" * len(REFS)]
        for channel, parameter, label in CHANNELS:
            for name, table in (("MPNet", mpnet), ("BERTScore", bert)):
                cells = [fmt(gain(table, M, channel, parameter, p, ref)) for ref, _ in REFS]
                lines.append(f"| {label} | {name} | " + " | ".join(cells) + " |")
        lines.append("")
    return "\n".join(lines)


def latex_rows(mpnet: dict, bert: dict, M: str = "2", p: str = "0.5") -> list[str]:
    rows = []
    for channel, parameter, label in CHANNELS:
        cells = []
        for table in (mpnet, bert):
            for ref, _ in REFS:
                g = gain(table, M, channel, parameter, p, ref)
                cells.append("--" if g is None else (f"${g[0]:+.3f}$" if (g[1] > 0 or g[2] < 0) else f"${g[0]:+.3f}^\\dagger$"))
        rows.append(f"{LATEX[label]} & " + " & ".join(cells) + r"\\")
    return rows


def main(argv=None) -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", default="results/channel/coco_k12")
    parser.add_argument("--out", default="docs/channel_bertscore_tables.md")
    args = parser.parse_args(argv)
    mpnet = load(Path(args.results) / "summary.csv")
    bert = load(Path(args.results) / "summary_bertscore.csv")
    Path(args.out).write_text(markdown(mpnet, bert) + "\n")
    print("\n".join(latex_rows(mpnet, bert)))


if __name__ == "__main__":
    main()
